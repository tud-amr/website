// Writes /assets/vendor/bootstrap-icons/icons.css with only the Bootstrap Icons the site uses
// (classes like `bi bi-github` in any page), instead of the full 2,000-icon stylesheet.
import fs from 'node:fs';
import path from 'node:path';

const ICONS = JSON.parse(fs.readFileSync('node_modules/bootstrap-icons/font/bootstrap-icons.json', 'utf8'));

function htmlFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return p.endsWith(path.join('_site', 'assets')) ? [] : htmlFiles(p);
    return e.name.endsWith('.html') ? [p] : [];
  });
}

export function writeIconCss(outputDir) {
  const used = new Set();
  for (const file of htmlFiles(outputDir)) {
    for (const [, name] of fs.readFileSync(file, 'utf8').matchAll(/\bbi-([a-z0-9-]+)/g)) if (ICONS[name]) used.add(name);
  }
  const rules = [...used].sort().map((name) => `.bi-${name}::before { content: "\\${ICONS[name].toString(16)}"; }`);
  const css = `/* Bootstrap Icons v1.11.3 (MIT), only the ${used.size} icons this site uses. Generated by src/lib/icons.mjs. */
@font-face { font-display: block; font-family: "bootstrap-icons"; src: url("bootstrap-icons.woff2") format("woff2"); }
.bi::before, [class^="bi-"]::before, [class*=" bi-"]::before {
  display: inline-block; font-family: bootstrap-icons !important; font-style: normal; font-weight: normal !important;
  font-variant: normal; text-transform: none; line-height: 1; vertical-align: -0.125em;
  -webkit-font-smoothing: antialiased; -moz-osx-font-smoothing: grayscale;
}
${rules.join('\n')}
`;
  const dir = path.join(outputDir, 'assets/vendor/bootstrap-icons');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'icons.css'), css);
  return used.size;
}
